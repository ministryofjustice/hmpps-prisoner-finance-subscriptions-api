CREATE TABLE revinfo (
     rev BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     revtstmp TIMESTAMP WITH TIME ZONE NOT NULL
);

COMMENT ON TABLE revinfo IS 'Records all revisions';

COMMENT ON COLUMN revinfo.rev IS 'Primary key. An integer generated by the application. [Sensitivity: NONE]';
COMMENT ON COLUMN revinfo.revtstmp IS 'The timestamp for the audit log. [Sensitivity: NONE]';

CREATE TABLE subscriptions_aud (
  subscription_id UUID NOT NULL,
  rev BIGINT NOT NULL,
  revtype SMALLINT NOT NULL,
  legacy_payment_profile_id BIGINT,
  amount                    BIGINT,
  payment_schedule            VARCHAR(20),
  start_date                date,
  end_date                  date,
  subscription_type         VARCHAR(255),
  reference                 VARCHAR(255),
  created_by                VARCHAR(255),
  created_at                TIMESTAMP WITH TIME ZONE,
  prison_id                 VARCHAR(10),
  prison_number             VARCHAR(10),
  sub_account_ref           VARCHAR(10),

  CONSTRAINT pk_subscriptions_aud
      PRIMARY KEY (subscription_id, rev),

  CONSTRAINT fk_subscriptions_aud_revision
      FOREIGN KEY (rev) REFERENCES revinfo (rev)
);

CREATE INDEX idx_subscriptions_aud_rev ON subscriptions_aud (rev);

COMMENT ON TABLE subscriptions_aud IS 'A record of a change to a subscription for audit purposes.';


COMMENT ON COLUMN subscriptions_aud.subscription_id IS 'Primary key. A UUIDv7 generated by the application, used as the subscriptions''s permanent public identifier across DPS. [Sensitivity: NONE]';
COMMENT ON COLUMN subscriptions_aud.rev IS 'Revision of the change for subscription entity. [Sensitivity: NONE]';
COMMENT ON COLUMN subscriptions_aud.revtype IS 'Type of the revision of the change for subscription entity. [Sensitivity: NONE]';
COMMENT ON COLUMN subscriptions_aud.subscription_id IS 'Primary key. A UUIDv7 generated by the application, used as the subscription''s permanent public identifier across DPS. [Sensitivity: NONE]';
COMMENT ON COLUMN subscriptions_aud.legacy_payment_profile_id IS 'Unique identifier from the legacy payment profile in NOMIS associated with this subscription. [Sensitivity: NONE]';
COMMENT ON COLUMN subscriptions_aud.amount IS 'Subscription fee amount in pence. [Sensitivity: OFFICIAL-SENSITIVE]';
COMMENT ON COLUMN subscriptions_aud.payment_schedule  IS 'Payment schedule on which the recurring payment is processed (e.g. MONDAY). [Sensitivity: NONE]';
COMMENT ON COLUMN subscriptions_aud.start_date IS 'Date from which the subscription becomes active. [Sensitivity: NONE]';
COMMENT ON COLUMN subscriptions_aud.end_date IS 'Optional end date when the subscription was or will be terminated. [Sensitivity: NONE]';
COMMENT ON COLUMN subscriptions_aud.subscription_type IS 'Type or code representing the transaction type (e.g. TELE, LIB, NEWS). [Sensitivity: NONE]';
COMMENT ON COLUMN subscriptions_aud.reference IS 'Optional reference note or external Identifier associated with the subscription. [Sensitivity: NONE]';
COMMENT ON COLUMN subscriptions_aud.created_by IS 'Username or system identifier of the account that created the record. [Sensitivity: STAFF]';
COMMENT ON COLUMN subscriptions_aud.created_at IS 'Timestamp (UTC) when the record was created. [Sensitivity: NONE]';
COMMENT ON COLUMN subscriptions_aud.prison_id IS 'Identifier/code for the prison facility where the subscription is active i.e "LEI". [Sensitivity: PERSONAL]';
COMMENT ON COLUMN subscriptions_aud.prison_number IS 'Prison number on DPS associated with the subscription. [Sensitivity: PERSONAL]';
COMMENT ON COLUMN subscriptions_aud.sub_account_ref IS 'Reference code for the specific prisoner sub-account used for billing i.e "CASH". [Sensitivity: NONE]';
