-- Data dictionary for the subscriptions schema.
--
-- These comments are read by SchemaSpy (published to GitHub Pages) and by anything else that reads
-- pg_description, including the CSV export for the MOJ Data Catalogue / Glue. Keep them updated when
-- columns are added or their meaning changes - SchemaCommentsTest fails the build if a table or column
-- has no comment.
--
-- Every column comment ends with a sensitivity classification:
--
--   [Sensitivity: NONE]                - not personal data in itself (keys, timestamps, process flags,
--                                        and the reference data in the constant_* tables)
--   [Sensitivity: PERSONAL]            - personal data about a prisoner: identifies or locates them
--   [Sensitivity: STAFF]               - personal data about a member of staff, typically the username
--                                        that performed an action
--   [Sensitivity: SPECIAL-CATEGORY]    - UK GDPR Article 9 data (health, sexuality, religion, race,
--                                        gender reassignment) or criminal offence data under Article 10
--   [Sensitivity: OFFICIAL-SENSITIVE]  - not personal data, but damaging if disclosed
--
-- STAFF is still personal data and still in scope for a staff member's own subject access request. It is
-- separated from PERSONAL so that an extract about prisoners can be reasoned about without staff columns
-- inflating the count, and so staff data can be dropped or pseudonymised independently.

------------------------------------------------------------------------------------------------
-- subscriptions - the record describing a subscription itself
------------------------------------------------------------------------------------------------

COMMENT ON TABLE subscriptions IS 'A record of a subscription for a prisoner i.e. for television or newspaper.';

COMMENT ON COLUMN subscriptions.subscription_id IS 'Primary key. A UUIDv7 generated by the application, used as the subscription''s permanent public identifier across DPS. [Sensitivity: NONE]';
COMMENT ON COLUMN subscriptions.legacy_payment_profile_id IS 'Unique identifier from the legacy payment profile in NOMIS associated with this subscription. [Sensitivity: NONE]';
COMMENT ON COLUMN subscriptions.amount IS 'Subscription fee amount in pence. [Sensitivity: OFFICIAL-SENSITIVE]';
COMMENT ON COLUMN subscriptions.day_of_payment IS 'Day of the week on which the recurring payment is processed (e.g. MONDAY). [Sensitivity: NONE]';
COMMENT ON COLUMN subscriptions.start_date IS 'Date from which the subscription becomes active. [Sensitivity: NONE]';
COMMENT ON COLUMN subscriptions.end_date IS 'Optional end date when the subscription was or will be terminated. [Sensitivity: NONE]';
COMMENT ON COLUMN subscriptions.subscription_type IS 'Type or code representing the transaction type (e.g. TELE, LIB, NEWS). [Sensitivity: NONE]';
COMMENT ON COLUMN subscriptions.reference IS 'Optional reference note or external Identifier associated with the subscription. [Sensitivity: NONE]';
COMMENT ON COLUMN subscriptions.created_by IS 'Username or system identifier of the account that created the record. [Sensitivity: STAFF]';
COMMENT ON COLUMN subscriptions.created_at IS 'Timestamp (UTC) when the record was created. [Sensitivity: NONE]';
COMMENT ON COLUMN subscriptions.prison_id IS 'Identifier/code for the prison facility where the subscription is active i.e "LEI". [Sensitivity: PERSONAL]';
COMMENT ON COLUMN subscriptions.prison_number IS 'Prison number on DPS associated with the subscription. [Sensitivity: PERSONAL]';
COMMENT ON COLUMN subscriptions.sub_account_ref IS 'Reference code for the specific prisoner sub-account used for billing i.e "CASH". [Sensitivity: NONE]';

------------------------------------------------------------------------------------------------
-- idempotency_keys - the record documenting used idempotency keys
------------------------------------------------------------------------------------------------


COMMENT ON TABLE idempotency_keys IS 'Stores idempotency keys to ensure duplicate subscription creation requests are handled safely and atomically.';

COMMENT ON COLUMN idempotency_keys.idempotency_key_id IS 'Primary key. Unique UUID idempotency key provided by or generated for the request to ensure idempotent processing. [Sensitivity: NONE]';
COMMENT ON COLUMN idempotency_keys.subscription_id IS 'Foreign key referencing the associated subscription. [Sensitivity: NONE]';